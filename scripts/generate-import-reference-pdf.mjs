import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { chromium } from '@playwright/test';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const manifestPath = path.join(repoRoot, 'data', 'import-benchmark-reference-us-v2.gold.json');
const outputPath = path.join(repoRoot, 'data', 'import-benchmark-reference-us-v2.pdf');
const manifest = JSON.parse(await fs.readFile(manifestPath, 'utf8'));

function escapeHTML(value) {
  return String(value ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

function markerFlag(marker) {
  if (Number(marker.value) < Number(marker.refMin)) return 'LOW';
  if (Number(marker.value) > Number(marker.refMax)) return 'HIGH';
  return '';
}

function renderSection(title, markers) {
  const rows = markers.map(marker => {
    const flag = markerFlag(marker);
    return `<tr>
      <td>${escapeHTML(marker.rawName)}</td>
      <td class="number">${escapeHTML(marker.value)}</td>
      <td class="flag ${flag.toLowerCase()}">${flag}</td>
      <td>${escapeHTML(marker.unit || '—')}</td>
      <td>${escapeHTML(marker.refMin)} – ${escapeHTML(marker.refMax)}</td>
    </tr>`;
  }).join('');
  return `<section>
    <h2>${escapeHTML(title)}</h2>
    <table>
      <thead><tr><th>Test</th><th>Result</th><th>Flag</th><th>Units</th><th>Reference interval</th></tr></thead>
      <tbody>${rows}</tbody>
    </table>
  </section>`;
}

function renderPage(pageNumber) {
  const pageMarkers = manifest.expected.markers.filter(marker => marker.page === pageNumber);
  const sections = [];
  for (const marker of pageMarkers) {
    let section = sections.find(item => item.title === marker.section);
    if (!section) {
      section = { title: marker.section, markers: [] };
      sections.push(section);
    }
    section.markers.push(marker);
  }
  return `<article class="report-page">
    <header>
      <div>
        <div class="lab-name">NORTHSTAR DIAGNOSTIC LABORATORY</div>
        <div class="lab-subtitle">Comprehensive Health Reference Report</div>
      </div>
      <div class="report-meta"><strong>FINAL REPORT</strong><br>Accession: GB-REF-US-260714</div>
    </header>
    <div class="fixture-warning">REFERENCE FIXTURE ONLY — NOT A REAL PATIENT OR LABORATORY REPORT</div>
    <div class="patient-grid">
      <div><span>Patient</span><strong>BENCHMARK SAMPLE</strong></div>
      <div><span>Date of birth</span><strong>01/01/1990</strong></div>
      <div><span>Specimen</span><strong>Serum / EDTA whole blood</strong></div>
      <div><span>Collected</span><strong>07/14/2026 08:15</strong></div>
      <div><span>Received</span><strong>07/14/2026 13:42</strong></div>
      <div><span>Reported</span><strong>07/15/2026 11:30</strong></div>
    </div>
    ${sections.map(section => renderSection(section.title, section.markers)).join('')}
    <footer>
      <span>Synthetic educational fixture generated by getbased. No clinical use.</span>
      <span>Page ${pageNumber} of 3</span>
    </footer>
  </article>`;
}

