export function configureDashboardViewFactory(createDashboardView: unknown) {
  if (typeof createDashboardView !== 'function') {
    throw new TypeError('configureDashboardViewFactory requires a dashboard view factory');
  }
  if (viewsComposition.dashboardView) return viewsComposition.dashboardView;

  retireProductionDashboard();
  viewsComposition.dashboardView = (createDashboardView as (deps: Parameters<NativeDashboardFactory>[0]) => unknown)({
    navigate,
    showRecommendations,
    showEmojiPicker,
    renderFocusCard,
    loadFocusCard,
    projectOnboardingBanner,
    projectAIConnectionReminder,
  });

  viewsComposition.lensPageHandlers = createLensPageHandlers({
    setupDropZone,
    buildDashboardWidgetContext: (viewsComposition.dashboardView as DashboardOperations).buildDashboardWidgetContext,
    projectLabsPriorityBanner: (viewsComposition.dashboardView as DashboardOperations).projectLabsPriorityBanner,
    projectDashboardQuickMarkersWidget: (viewsComposition.dashboardView as DashboardOperations).projectDashboardQuickMarkersWidget,
    projectDashboardKeyTrendsWidget: (viewsComposition.dashboardView as DashboardOperations).projectDashboardKeyTrendsWidget,
    projectDashboardGenomeWidget: (viewsComposition.dashboardView as DashboardOperations).projectDashboardGenomeWidget,
    projectDashboardWearableTilesWidget: (viewsComposition.dashboardView as DashboardOperations).projectDashboardWearableTilesWidget,
    projectDashboardInsightsListWidget: (viewsComposition.dashboardView as DashboardOperations).projectDashboardInsightsListWidget,
    projectDashboardRecommendationsWidget: (viewsComposition.dashboardView as DashboardOperations).projectDashboardRecommendationsWidget,
    projectFocusCard,
    loadFocusCard,
    getDashboardWidgetPrefs: (viewsComposition.dashboardView as DashboardOperations).getDashboardWidgetPrefs,
    getCachedRecommendationsCatalog: (viewsComposition.dashboardView as DashboardOperations).getCachedRecommendationsCatalog,
    refreshRecommendationsWhenCatalogReady: (viewsComposition.dashboardView as DashboardOperations).refreshRecommendationsWhenCatalogReady,
    getGlobalRecommendationCandidates: (viewsComposition.dashboardView as DashboardOperations).getGlobalRecommendationCandidates,
    getLensContentGrid,
    getLensWidgetChrome,
  });

  viewsComposition.recommendationActions = (createRecommendationActions as RecommendationConstructorOperations)({
    getActiveData,
    buildDashboardWidgetContext: (viewsComposition.dashboardView as DashboardOperations).buildDashboardWidgetContext,
    getCachedRecommendationsCatalog: (viewsComposition.dashboardView as DashboardOperations).getCachedRecommendationsCatalog,
    getGlobalRecommendationCandidates: (viewsComposition.dashboardView as DashboardOperations).getGlobalRecommendationCandidates,
    setRecommendationState: (...args) => getDashboardView().setRecommendationState(...args),
  });

  return viewsComposition.dashboardView;
}
