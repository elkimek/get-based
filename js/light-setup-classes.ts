export type SetupRecipeHook = keyof typeof setupMetadata;
const setupStyles: Readonly<Record<string, string>> = setupMetadata;

export function setupClasses(hooks: string): string {
  return hooks.split(/\s+/).filter(Boolean).map(hook => `${hook} ${setupStyles[hook] || ''}`).join(' ');
}

export function setupChipClasses(chip: LightSetupChip): string {
  return setupClasses([
    'light-setup-chip', `light-setup-chip-${chip.kind}`,
    chip.accent ? `light-setup-chip-home-${chip.accent}` : '',
    chip.tier !== undefined ? `light-setup-chip-tier-${chip.tier}` : '',
  ].join(' '));
}
