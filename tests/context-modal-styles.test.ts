import {currentContextRuntime,requireExactContextRuntime} from './helpers/migration-review-context-runtime.js';
import {describe,expect,it} from 'vitest';
import fs from 'node:fs';
import path from 'node:path';
import {createHash} from 'node:crypto';
import postcss from 'postcss';
import {contextEditorOwnership,contextProfileOwnership,sharedModalOwnership,compileContextEditorStyles} from '../scripts/context-modal-style-ownership.mjs';
import {compileModalPresentationStyles} from '../scripts/modal-presentation-style-ownership.mjs';
import {compileSupplementProfileStyles} from '../scripts/supplement-form-style-ownership.mjs';
const root=process.cwd();
const hashes={
  "context-editor": {
    "base-original": "40a9d7a686e9cf0fac4029082753cc699e6018116e4b6fd6f9b084eeee30e8a8",
    "original": "7fd301d1b7dadfe3e373ad4f867b41809c6124428cca64d66b7f3b6f289bfc2c"
  },
  "context-profile": {
    "base-original": "a561650eb74726fceea08ec83935358ae38223614d314e75a237fb7c16a017d1",
    "original": "1c62ef031bced4fe4f75455303ceea70c0bdc736ea14c5f8e5e977a4238e07d4"
  },
  "modal-shared": {
    "base-original": "274e3689ad31cb4d39851f72f273888152c6d29ef1f81885df4c2b096c119bd6",
    "original": "9878ebe61a99ea96865684ac102ea1dadeec8a1455536e1cc4550478cb331649"
  }
} as const;
const lanes=[['context-editor',contextEditorOwnership,compileContextEditorStyles,59,196,0],['context-profile',contextProfileOwnership,compileSupplementProfileStyles,30,132,2],['modal-shared',sharedModalOwnership,compileModalPresentationStyles,82,355,3]] as const;
for(const [name,ownership,compile,receivers,declarations,keyframeDeclarations] of lanes)describe(name+' complete remaining Tailwind ownership',()=>{
 const inputPath=path.join(root,'css',name+'.base.css'),input=fs.readFileSync(inputPath,'utf8');
 const original=fs.readFileSync(path.join(root,'tests/fixtures',name+'-remaining-base-original.css'),'utf8');
 const originalRuntime=fs.readFileSync(path.join(root,'tests/fixtures',name+'-remaining-original.css'),'utf8');
 async function exact(source:string){const result=await compile(source,inputPath,root);expect(result.css).toBe(original);return result;}
 it('keeps immutable native bases and complete emitted stylesheets byte exact',async()=>{
  expect(createHash('sha256').update(original).digest('hex')).toBe(hashes[name]['base-original']);
  expect(createHash('sha256').update(originalRuntime).digest('hex')).toBe(hashes[name].original);
  expect(ownership.receivers).toHaveLength(receivers);expect(ownership.declarationCount).toBe(declarations);
  const expected=postcss.parse(original),selected=ownership.receivers.map(([,selector,condition])=>{const rules:postcss.Rule[]=[];expected.walkRules(rule=>{if(rule.selector!==selector)return;const media=rule.parent?.type==='atrule'?rule.parent.params:null;if(media===condition)rules.push(rule);});expect(rules).toHaveLength(1);return rules[0]!;});
  expect(selected.reduce((count,rule)=>count+rule.nodes.filter(node=>node.type==='decl').length,0)).toBe(declarations);
  const tree=postcss.parse(input);let unowned=0,frames=0;tree.walkDecls(decl=>{if(decl.parent?.type==='atrule'&&decl.parent.name==='utility')return;let keyframe=false;for(let p:postcss.Node|undefined=decl.parent;p;p=p.parent)if(p.type==='atrule'&&(p as postcss.AtRule).name==='keyframes')keyframe=true;if(keyframe)frames++;else unowned++;});expect(unowned).toBe(0);expect(frames).toBe(keyframeDeclarations);
  const compiled = await exact(input), runtime = fs.readFileSync(path.join(root,'css',name+'.css'),'utf8');
  if (name === 'modal-shared') expect(runtime).toBe(originalRuntime);
  else {
   const entry = name === 'context-editor' ? 'context-editor.tailwind.css' : 'context-catalog.tailwind.css';
   const prefix = `/* Generated by npm run styles:build; edit ${name}.base.css or ${entry}. */\n` + original.trimEnd() + '\n\n';
   expect(originalRuntime.startsWith(prefix)).toBe(true); expect(runtime.startsWith(prefix)).toBe(true);
   requireExactContextRuntime(runtime, await currentContextRuntime(name, compiled.css, root));
  }
 });
 if(name !== 'modal-shared') it('rejects changed current native prefix, generated tail, or trailing bytes while retaining the original oracle',async()=>{
  const compiled=await exact(input),expected=await currentContextRuntime(name,compiled.css,root);
  const current=fs.readFileSync(path.join(root,'css',name+'.css'),'utf8');requireExactContextRuntime(current,expected);
  for(const changed of ['/* foreign prefix */'+current,current.replace('gb-theme','foreign-theme'),current+'\n/* foreign tail */']) {
   expect(changed).not.toBe(current);expect(()=>requireExactContextRuntime(changed,expected)).toThrow();
  }
 });
 const [utility,selector]=ownership.receivers[0]!;
 const recipe=postcss.parse(input).nodes.find(n=>n.type==='atrule'&&n.name==='utility'&&n.params===utility);if(recipe?.type!=='atrule'||!recipe.nodes)throw new Error('Expected owned recipe');
 const declaration=recipe.nodes.find(n=>n.type==='decl');if(declaration?.type!=='decl')throw new Error('Expected declaration');
 const valueStart=declaration.source!.start!.offset!,valueEnd=declaration.source!.end!.offset!;
 const alterDeclaration=(suffix:string)=>{const copy=declaration.clone();copy.value+=suffix;return input.slice(0,valueStart)+copy.toString()+(input[valueEnd-1]===';'?';':'')+input.slice(valueEnd);};
 const mutations:Array<[string,(source:string)=>string]>=[
 ['changed native value',()=>alterDeclaration('__changed')],
 ['changed priority',()=>{const copy=declaration.clone();copy.important=!copy.important;return input.slice(0,valueStart)+copy.toString()+(input[valueEnd-1]===';'?';':'')+input.slice(valueEnd);}],
 ['unknown recipe',s=>s.replace('@utility '+utility,'@utility foreign-recipe')],
 ['unknown apply',s=>s.replace('@apply gb:'+utility+';','@apply gb:foreign-recipe;')],
 ['extra receiver declaration',s=>s.replace('@apply gb:'+utility+';','@apply gb:'+utility+'; color:red;')],
 ['duplicate selector',s=>s+'\n'+selector+' { color:red; }'],
 ['same-count selector replacement',s=>s.replace(selector+' { @apply','.foreign-current-owner { @apply')],
 ['foreign authored comment',s=>s+'\n/* unreviewed foreign bytes */'],
 ['additional foreign rule',s=>s+'\n.foreign-current-style {color:red;}'],
 ];
 const media=ownership.receivers.find(row=>row[2]!==null)?.[2];if(media)mutations.push(['changed media ancestry',s=>s.replace('@media '+media,'@media (max-width: 1px)')]);
 if(keyframeDeclarations)mutations.push(['changed animation definition',s=>s.replace('@keyframes ','@keyframes foreign-')]);
 it.each(mutations)('rejects %s without changing the native oracle',async(_label,mutate)=>{const changed=mutate(input);expect(changed).not.toBe(input);await expect(exact(changed)).rejects.toThrow();});
});
