import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import {execFileSync} from 'node:child_process';

type Lane = 'context-editor' | 'context-profile';
const entries: Record<Lane, string> = {'context-editor': 'context-editor.tailwind.css', 'context-profile': 'context-catalog.tailwind.css'};
const expected = new Map<string, Promise<string>>();
/** Match production compileStyles exactly: current CLI source scanning, minifier,
 * canonical compiled base, generated notice and byte separators. Old utilities
 * remain immutable historical evidence; current utilities are regenerated whole. */
export function currentContextRuntime(lane: Lane, base: string, root: string): Promise<string> {
  const key = lane + '\0' + root + '\0' + base;
  let value = expected.get(key);
  if (!value) {
    value = (async () => {
      const directory = await fs.mkdtemp(path.join(os.tmpdir(), 'getbased-context-review-'));
      try {
        const output = path.join(directory, 'utilities.css'), entry = entries[lane];
        execFileSync(process.execPath, [path.join(root, 'node_modules/@tailwindcss/cli/dist/index.mjs'),
          '--input', path.join(root, 'css', entry), '--output', output, '--minify'], {cwd: root, stdio: ['ignore', 'ignore', 'pipe']});
        const utilities = await fs.readFile(output, 'utf8');
        return `/* Generated by npm run styles:build; edit ${lane}.base.css or ${entry}. */\n`
          + base.trimEnd() + '\n\n' + utilities.trimEnd() + '\n';
      } finally {await fs.rm(directory, {recursive: true, force: true});}
    })();
    expected.set(key, value);
  }
  return value;
}
export function requireExactContextRuntime(actual: string, expected: string): void {
  assert.equal(actual === expected, true, 'Complete current native-prefix and generated Tailwind-tail bytes');
}
